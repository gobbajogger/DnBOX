"""Generate firmware/src/app/ui_gfinal_map.h from tools/gfinal/parameter-map.json.

TYPE_MAPPED rows win; HOLD/DYNAMIC rows take their candidate type; READ_ONLY rows
have none. Firmware descriptors are keyed by their normalized name (<= 6 chars).
The few names whose meaning depends on the engine are resolved in ui_gfinal_glyph_of().
"""
import json, re, sys
from pathlib import Path
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE)); import gfinal  # noqa: E402
ids = list(gfinal.GLYPHS)
ENG = ['Chicago', 'Miami', '909', '808', 'FX', 'Master', 'BREAK', 'Mix', 'SuperJ6 compact', 'Synth One compact']
AMBIG = {'attack', 'tune', 'pitch', 'tone', 'filter'}   # resolved in C
def key(n): return re.sub('[^a-z0-9]', '', n.lower())[:6]
m = json.load(open(HERE / 'parameter-map.json'))
names, kinds, gen = {}, {}, {}
# TYPE_MAPPED first; HOLD/DYNAMIC rows then take their candidate type, because
# their 0.0.26 bodies are gone (XIP). READ_ONLY rows draw no glyph.
rows = [x for x in m if x['status'] == 'TYPE_MAPPED'] + [x for x in m if x['status'] in ('HOLD', 'DYNAMIC')]
for x in rows:
    if not x['glyph'] or x['glyph'] not in ids: continue
    held = x['status'] != 'TYPE_MAPPED'
    g = ids.index(x['glyph'])
    if x['engine'] in ENG:
        k = key(x['name'])
        if k in AMBIG: continue
        if held: names.setdefault(k, g); continue
        if names.get(k, g) != g: raise SystemExit(f'ambiguous name {k}: {ids[names[k]]} vs {x["glyph"]}')
        names[k] = g
    elif x['engine'] == 'Common UI':
        kind = int(x['group'].split()[1]); c = int(x['id'].split(':')[2])
        if held: (gen.setdefault(c, g) if kind == 9 else kinds.setdefault(kind, g)); continue
        if kind == 9: gen[c] = g
        elif kinds.get(kind, g) != g: raise SystemExit(f'kind {kind} ambiguous')
        else: kinds[kind] = g
ks = sorted(names)
out = ['/* SPDX-License-Identifier: GPL-3.0-only */',
       '/* Generated by tools/gfinal/gen_map.py from parameter-map.json; do not edit. */',
       '#ifndef UI_GFINAL_MAP_H', '#define UI_GFINAL_MAP_H',
       f'#define GF_NAME_N {len(ks)}',
       'static const char gf_name_key[GF_NAME_N][6] = {' + ','.join('{' + ','.join(f"'{ch}'" for ch in k.ljust(6, '\0')).replace("'\x00'", '0') + '}' for k in ks) + '};',
       'static const uint8_t gf_name_glyph[GF_NAME_N] = {' + ','.join(str(names[k]) for k in ks) + '};',
       f'#define GF_KIND_N {max(kinds) + 1}',
       'static const uint8_t gf_kind_glyph[GF_KIND_N] = {' + ','.join(str(kinds.get(i, 255)) for i in range(max(kinds) + 1)) + '};',
       'static const uint8_t gf_gen_glyph[8] = {' + ','.join(str(gen.get(i, 255)) for i in range(8)) + '};',
       '#endif', '']
dst = HERE.parents[1] / 'firmware' / 'src' / 'app' / 'ui_gfinal_map.h'
text = '\n'.join(out)
if '--check' in sys.argv:
    sys.exit(0 if dst.read_text() == text else (print('ui_gfinal_map.h is stale: run tools/gfinal/gen_map.py') or 1))
dst.write_text(text); print(f'{len(ks)} names, {len(kinds)} kinds, {len(gen)} sequencer rows')
