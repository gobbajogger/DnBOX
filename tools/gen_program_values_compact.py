#!/usr/bin/env python3
"""Lossless binary32 dictionary and unpadded immutable factory-name storage.

Reads the pinned original metadata, does not rewrite it. Never rounds a control
or synthesizes coefficients. Generated values are tested against every raw cell.
"""
from pathlib import Path
import re,struct,hashlib,sys
ROOT=Path(__file__).resolve().parents[1]
D=ROOT/'experiments/original_synth'
PINS={'miami_program_private.h':'5b950f6441f38e68c36d303a55361ce1d1e75c23ec05d7a5314fa2c32c3aa460','chicago_program_private.h':'b95ed765e55886ed7d1e52ebb06b43d5026743ec6dd17d9a9cf6cc34e9dcc309'}
s={n:(D/n).read_text() for n in PINS}
for n,pin in PINS.items():
 if hashlib.sha256((D/n).read_bytes()).hexdigest()!=pin:raise SystemExit('changed immutable program metadata: '+n)
def values(file,name,n):
 m=re.search(r'\b'+name+r'\[[^=]+=(.*?);',s[file],re.S)
 a=[struct.unpack('<I',struct.pack('<f',float.fromhex(v[:-1])))[0] for v in re.findall(r'[-+]?0x[0-9a-f.]+p[-+][0-9]+f',m[1])]
 assert len(a)==n,(name,len(a));return a
factory=values('miami_program_private.h','original_miami_factory_macro',540)
mb=values('miami_program_private.h','original_miami_base',109);cb=values('chicago_program_private.h','original_chicago_base',117)
# Existing factories have neutral performance inputs; preserve those exact words.
assert all(factory[f*18+16:f*18+18]==[0x3f000000,0] for f in range(30))
factory=[factory[f*18+p] for f in range(30) for p in range(16)]
dictionary=[]
for u in factory+mb+cb:
 if u not in dictionary:dictionary.append(u)
assert len(dictionary)<=256
code=lambda a:[dictionary.index(u) for u in a]
# The same byte encodes either a dictionary value or a live target. Only the
# native lookup table is retained in the linked synth; the raw base accessor
# remains available to the metadata oracle.
mapping=re.search(r'original_chicago_mappings\[29\]=\{(.*?)\};',s['chicago_program_private.h'],re.S)
native_ids=[int(v) for v in re.findall(r'\{(\d+),',mapping[1])]
assert len(native_ids)==len(set(native_ids))==29
chicago_native=code(cb)
assert len(dictionary)+len(native_ids)<=256
for slot,native_id in enumerate(native_ids):
 chicago_native[native_id]=len(dictionary)+slot
names=re.findall(r'"(.*?)"',re.search(r'original_miami_factory_name\[30\]\[24\]=\{(.*?)\};',s['miami_program_private.h'],re.S)[1]);assert len(names)==30
payload=[];offset=[]
for name in names:offset.append(len(payload));payload+=list(name.encode('ascii')+b'\0')
def arr(ctype,name,a,fmt=str):
 return 'static const '+ctype+' '+name+'['+str(len(a))+']={\n'+''.join(' '+','.join(fmt(v) for v in a[i:i+16])+',\n' for i in range(0,len(a),16))+'};\n'
out='/* SPDX-License-Identifier: GPL-3.0-only */\n/* Generated by tools/gen_program_values_compact.py; exact original metadata. */\n#pragma once\n#include <stdint.h>\n'
# Weak, immutable definition keeps each API standalone-linkable while the full
# product retains one identical dictionary. No global linker coalescing flag.
out+='__attribute__((weak)) const uint32_t original_program_value_words['+str(len(dictionary))+']={\n'+''.join(' '+','.join(f'0x{v:08x}u' for v in dictionary[i:i+8])+',\n' for i in range(0,len(dictionary),8))+'};\n'
out+='static inline float compact_program_value(unsigned code){union{uint32_t u;float f;}v;v.u=original_program_value_words[code];return v.f;}\n'
out+='#ifdef ORIGINAL_PROGRAM_VALUES_MIAMI\n'+arr('uint8_t','compact_miami_factory_codes',code(factory))+arr('uint8_t','compact_miami_base_codes',code(mb))+arr('uint16_t','compact_miami_name_offsets',offset)+arr('char','compact_miami_names',payload)
out+='static inline float compact_miami_factory_value(unsigned f,unsigned p){return p<16u?compact_program_value(compact_miami_factory_codes[f*16u+p]):p==16u?0.5f:0.0f;}\n'
out+='static inline float compact_miami_base_value(unsigned i){return compact_program_value(compact_miami_base_codes[i]);}\n'
out+='static inline const char *compact_miami_factory_name(unsigned f){return compact_miami_names+compact_miami_name_offsets[f];}\n#endif\n'
out+='#ifdef ORIGINAL_PROGRAM_VALUES_CHICAGO\n'+arr('uint8_t','compact_chicago_base_codes',code(cb))+arr('uint8_t','compact_chicago_native_codes',chicago_native)+'static inline float compact_chicago_base_value(unsigned i){return compact_program_value(compact_chicago_base_codes[i]);}\n#endif\n'
# Each row stores the authored macro dictionary indices. A small per-column
# palette pays for itself only when its narrower field saves more than the
# palette costs. Reuse the existing Miami/native dictionary for shared words.
def chicago_factory_header():
    source = s['chicago_program_private.h']
    original = values('chicago_program_private.h', 'original_chicago_factory_dictionary', 309)
    codes = re.search(r'original_chicago_factory_codes\[2005\]=\{(.*?)\};', source, re.S)
    packed = int.from_bytes(bytes(map(int, codes[1].split(','))), 'little')
    words = [original[(packed >> (9 * i)) & 511] for i in range(81 * 22)]
    extra = sorted(set(words) - set(dictionary))
    all_words = dictionary + extra
    indices = {word: i for i, word in enumerate(all_words)}
    assert len(all_words) <= 512
    # The four consecutive high bytes of the extra words are implicit in their
    # sorted indices. Store the original three low bytes without rounding.
    high = sorted(set(word >> 24 for word in extra))
    assert high == list(range(high[0], high[-1] + 1))
    limits = [sum(word >> 24 < group for word in extra) for group in high[1:]]
    high_byte = str(high[0]) + ''.join(f' + (i >= {limit}u)' for limit in limits)
    payload = [byte for word in extra for byte in word.to_bytes(4, 'little')[:3]]
    palettes, fields, rows = [], [], [0] * 81
    shift = 0
    for column in range(22):
        values_at_column = [indices[word] for word in words[column::22]]
        palette = sorted(set(values_at_column))
        width = (len(palette) - 1).bit_length()
        if 81 * (9 - width) > 16 * len(palette):
            indices_at_column = [palette.index(code) for code in values_at_column]
            offset = len(palettes)
            palettes.extend(palette)
        else:
            width, offset, indices_at_column = 9, 0, values_at_column
        fields.append((shift, width, offset))
        for row, code in enumerate(indices_at_column):
            rows[row] |= code << shift
        shift += width
    bitstream = sum(row << (number * shift) for number, row in enumerate(rows))
    # The decoder reads two bytes even for the final zero-width field.
    packed_rows = list(bitstream.to_bytes((81 * shift + 7) // 8, 'little')) + [0, 0]
    assert shift < 256 and len(palettes) < 256
    section = '#if defined(ORIGINAL_PROGRAM_VALUES_CHICAGO)\n'
    section += arr('uint8_t', 'compact_chicago_factory_low', payload)
    section += arr('uint16_t', 'compact_chicago_factory_palette', palettes)
    section += arr('uint8_t', 'compact_chicago_factory_rows', packed_rows)
    section += 'static const struct { uint8_t shift, width, offset; } compact_chicago_field[22]={\n'
    section += ''.join(' {' + ','.join(map(str, field)) + '},\n' for field in fields) + '};\n'
    section += f'''static inline float compact_chicago_factory_value(unsigned factory, unsigned parameter)
{{
    unsigned bit = factory * {shift}u + compact_chicago_field[parameter].shift;
    unsigned width = compact_chicago_field[parameter].width;
    const uint8_t *src = compact_chicago_factory_rows + bit / 8;
    unsigned code = ((src[0] | ((unsigned)src[1] << 8)) >> (bit & 7)) & ((1u << width) - 1);
    if (width < 9) code = compact_chicago_factory_palette[compact_chicago_field[parameter].offset + code];
    if (code < {len(dictionary)}u) return compact_program_value(code);
    unsigned i = code - {len(dictionary)}u;
    const uint8_t *low = compact_chicago_factory_low + 3 * i;
    uint32_t high = {high_byte};
    union {{ uint32_t u; float f; }} value;
    value.u = (high << 24) | ((uint32_t)low[2] << 16) | ((uint32_t)low[1] << 8) | low[0];
    return value.f;
}}
#endif
'''
    return section

out += chicago_factory_header()
if len(sys.argv)>2:
 raise SystemExit('usage: gen_program_values_compact.py [OUTPUT_HEADER]')
destination=Path(sys.argv[1]) if len(sys.argv)==2 else D/'program_values_compact.h'
destination.write_text(out)
print('program values:',len(dictionary)*4+len(factory)+len(mb)+len(cb),'B + names',len(payload)+2*len(offset),'B; raw values/names3784 B; all words exact')
