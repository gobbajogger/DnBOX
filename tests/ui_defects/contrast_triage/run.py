"""Replay a source-bound exploratory contrast observer. Not a full UI gate."""
import argparse,hashlib,json,os,re,shutil,subprocess
from pathlib import Path

def sha(b):return hashlib.sha256(b).hexdigest()
def main():
 ap=argparse.ArgumentParser();ap.add_argument('--source',type=Path,required=True);ap.add_argument('--output',type=Path,required=True);a=ap.parse_args();src=a.source.resolve();out=a.output.resolve();out.mkdir(parents=True,exist_ok=False);frozen=out/'source';frozen.mkdir()
 for n in ('firmware','host','tests','tools','assets','experiments'):shutil.copytree(src/n,frozen/n,symlinks=True,ignore=shutil.ignore_patterns('__pycache__'))
 inputs={str(p.relative_to(frozen)):sha(p.read_bytes()) for p in frozen.rglob('*') if p.is_file()};(out/'source-inputs.json').write_text(json.dumps(inputs,indent=2)+'\n')
 helper='tests/ui_defects/contrast_triage/';patch=(frozen/(helper+'observer.patch')).read_bytes();receipt_bytes=(frozen/(helper+'observer-inputs.json')).read_bytes()
 if sha(patch)!=inputs[helper+'observer.patch'] or sha(receipt_bytes)!=inputs[helper+'observer-inputs.json']:raise ValueError('Captured observer drift')
 receipt=json.loads(receipt_bytes)
 for path,pins in receipt.items():
  if inputs[path]!=pins['beforeSHA256']:raise ValueError('Source differs from reviewed observer input: '+path)
 subprocess.run(['git','apply','--check','-'],cwd=frozen,input=patch,check=True)
 subprocess.run(['git','apply','-'],cwd=frozen,input=patch,check=True)
 def verify():
  changed={p for p,h in inputs.items() if sha((frozen/p).read_bytes())!=h}
  if changed!=set(receipt):raise ValueError('Unexpected source changes: '+str(changed))
  for p,h in receipt.items():
   if sha((frozen/p).read_bytes())!=h['afterSHA256']:raise ValueError('Instrumented source drift: '+p)
 verify();results=[]
 for label,fixture in [('ordinary','ui_screen_inventory.c'),('lists','ui_overlay_inventory.c')]:
  env=os.environ.copy();env.update(SMC_UI_TEST_FILE='tests/host/'+fixture,SMC_UI_OUT=str(out/label))
  with (out/(label+'.log')).open('w')as log:r=subprocess.run(['sh','tests/host/smc_ui_test.sh'],cwd=frozen,env=env,stdout=log,stderr=subprocess.STDOUT)
  verify();log=(out/(label+'.log')).read_text();before_context=label=='ordinary';controls=[0,0];runtime=[0,0];collisions=0
  for line in log.splitlines():
   if line.startswith('CONTRAST_CONTEXT'):before_context=False
   m=re.match(r'CONTRAST_CANDIDATE decoration=([01]) ',line)
   if m:(controls if before_context else runtime)[int(m[1])]+=1
   if line.startswith('GLYPH_TEXT_INTERSECTION'):collisions+=1
  if r.returncode:raise ValueError('Producer failed: '+label)
  if label=='ordinary' and (controls!=[2,1] or 'CONTRAST_POSITIVE_CONTROLS PASS' not in log):raise ValueError('Positive-control admission failed')
  bounds=re.findall(r'^TEXT_BOUNDS (\d+) (\d+) (\d+) (\d+) (\d+)$',log,re.M)
  if len(bounds)!=1:raise ValueError('Missing logical-bound witness')
  results.append(dict(domain=label,screenRecords=len(re.findall(r'^SCREEN ',log,re.M)),positiveControlCandidates=controls,nonDecorativeAlphabeticOpaqueCandidates=runtime[0],decorativeCandidates=runtime[1],glyphBeforeTextIntersectionCalls=collisions,textBounds=list(map(int,bounds[0])),logSHA256=sha((out/(label+'.log')).read_bytes())))
 report=dict(schema='dnbox-contrast-triage/1',coverageComplete=False,inputManifestSHA256=sha((out/'source-inputs.json').read_bytes()),observerPatchSHA256=sha(patch),observerReceiptSHA256=sha(receipt_bytes),domains=results,limits='Exploratory immediate prepaint contrast of alphabetic text at fully opaque font pixels only. Four exact call sites classify incised decoration, never RGB color. Does not establish final visibility, every label/value, other themes, mixed backgrounds, minimum fonts, animation, all screens or check20/F2. Ordinary positive-control phase counted separately by explicit context boundary. Raw PNGs, if generated by the pre-existing diagnostic fixture, remain local and are not required publication.')
 (out/'report.json').write_text(json.dumps(report,indent=2)+'\n');print(json.dumps(report))
if __name__=='__main__':main()
