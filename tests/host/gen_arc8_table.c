/* Regenerate with gcc -O1 -ffp-contract=off -Ifirmware/src tests/host/gen_arc8_table.c. */
#include <stdio.h>
#include <stdint.h>
#include <string.h>
#include <assert.h>
#include "dsp/fastmath.h"
static float turns(float y, float x)
{
    float ax = fm_fabsf(x), ay = fm_fabsf(y), a = ax < ay ? ax / (ay + 1e-9f) : ay / (ax + 1e-9f), s = a * a, r;
    r = ((-0.0464964749f * s + 0.15931422f) * s - 0.327622764f) * s * a + a;   /* atan on [0, 1] */
    if (ay > ax)
        r = 1.57079637f - r;
    if (x < 0.0f)
        r = FM_PI - r;
    if (y < 0.0f)
        r = FM_TWO_PI - r;
    return r * (1.0f / FM_TWO_PI);
}

int main(void)
{
    puts("/* SPDX-License-Identifier: GPL-3.0-only */");
    puts("/* Generated by tests/host/gen_arc8_table.c with the original float arithmetic. */");
    uint32_t rows[15]={0}, codes[361]; unsigned n=0;
    const unsigned prefix[]={0x3f,0x3e,0x3d,0x3c,0x38};
    for (int y = -9; y <= 9; ++y) for (int x = -9; x <= 9; ++x) {
        float dx = (float)x + 0.5f - 0.5f, dy = (float)y + 0.5f - 0.5f;
        float d = fm_sqrtf(dx * dx + dy * dy), t;
        float a = fm_clampf(8.0f + 0.5f - d, 0.0f, 1.0f) * fm_clampf(d - (8.0f - 3.4f) + 0.5f, 0.0f, 1.0f);
        if (a <= 0.0f) continue;
        t = turns(dy, dx) - 0.375f;
        if (t < 0.0f) t += 1.0f;
        t /= 0.75f;
        if (t > 1.0f) continue;
        uint32_t bits; memcpy(&bits, &t, sizeof bits);
        unsigned coverage=(unsigned)(a*16.f+.5f), k=0;
        if (!coverage) continue;
        while(k<5 && prefix[k]!=(bits>>24))k++;
        assert(k<5 && x>=-8 && x<=8 && y>=-8 && y<=6);
        rows[y+8]|=1u<<(x+8);
        codes[n++]=(bits&0xffffffu)|((k*16+(coverage&15u))<<24);
    }
    puts("static const uint8_t arc8_prefix[] = {0x3f,0x3e,0x3d,0x3c,0x38};");
    puts("static const uint32_t arc8_rows[] = {");
    for(unsigned i=0;i<15;i++)printf("    0x%05xu,\n",rows[i]);
    puts("};\nstatic const uint32_t arc8_geometry[] = {");
    for(unsigned i=0;i<n;i++)printf("    0x%08xu,\n",codes[i]);
    puts("};");
    return 0;
}
