// Actual-app host pilot only. No native catalog or production admission.
import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
import {pathToFileURL,fileURLToPath} from 'node:url';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
const [binary,codecArg]=process.argv.slice(2);
const codecPath=codecArg??fileURLToPath(new URL('./dnr2_reference/browser_codec.mjs',import.meta.url));
if(!binary||!codecPath)throw Error('Provide actual-host binary and pinned browser codec path');
assert.equal(createHash('sha256').update(readFileSync(codecPath)).digest('hex'),'2ba77fa371114c978dc00d25f2205ff69593a9ab4f24a3a406c262426bdf50d2','Browser codec input must match pinned source');
const {encodeCommand,decodeReply,OP,STATUS}=await import(pathToFileURL(codecPath));
const manifest=spawnSync(binary,['--catalog'],{encoding:'utf8',timeout:60000});
assert.equal(manifest.status,0,manifest.stderr);
const catalog=JSON.parse(manifest.stdout);assert.equal(catalog.admitted,false);assert.equal(catalog.nativeAdmitted,false);
assert.equal(catalog.count,326);assert.equal(catalog.controls.length,catalog.count);
const makeup=catalog.diagnosticMasterMakeup;
assert.ok(catalog.controls.some(c=>c.id===makeup && c.kind===1));
const command=(op,request,extra={})=>({version:2,op,unit:1,unitHigh:[2,3,4],client:7,epoch:1,request,revision:1,control:0,token:0,value:0,...extra});
const hex=c=>Buffer.from(encodeCommand(c)).toString('hex');
const set=command(OP.SET,3,{control:makeup,value:23});
const lines=[hex(command(OP.HELLO,1,{unit:0,unitHigh:[0,0,0],epoch:0,revision:0})),hex(command(OP.OPEN,2,{epoch:0,revision:0})),hex(set),hex(command(OP.READ,4,{control:makeup,revision:2})), 'external 24',hex(set),hex(command(OP.SET,5,{control:makeup,value:25,revision:2})),'bad frame'];
const r=spawnSync(binary,['--serve'],{input:lines.join('\n')+'\n',encoding:'utf8',timeout:60000});
assert.equal(r.status,0,r.stderr);const output=r.stdout.trim().split('\n').map(x=>JSON.parse(x));
assert.equal(output.length,lines.length);
const reply=i=>decodeReply(Buffer.from(output[i].hex,'hex'));
assert.equal(reply(0).status,STATUS.OK);assert.equal(reply(0).control,catalog.count);
assert.equal(reply(0).value,catalog.crc);
assert.equal(reply(1).status,STATUS.OK);assert.equal(reply(2).status,STATUS.QUEUED);
assert.equal(reply(2).revision,2);assert.equal(reply(3).value,23);
assert.equal(output[4].value,24);assert.ok(output[4].revision>2);
assert.equal(reply(5).revision,output[4].revision);assert.equal(reply(6).status,STATUS.CONFLICT);
assert.equal(output[7].invalid,true);
console.log('PASS actual-app C wire/browser codec pilot: 8 exchanges; generated326-control descriptor table, one wire scalar, no endpoint admission');
